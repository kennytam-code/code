/** Small Artifact-authored style projection. Native chart bindings stay untouched. */
import fs from 'node:fs/promises';
import {Workbook, SpreadsheetFile} from '@oai/artifact-tool';
const root=new URL('../',import.meta.url),out=new URL('out/ah_readability_20261019/',root);
await fs.mkdir(out,{recursive:true});
const input=JSON.parse(await fs.readFile(new URL('inputs.json',out),'utf8'));
if(!input.rows.length)throw new Error('No observed chart data');
const wb=Workbook.create(),s=wb.worksheets.add('AH chart styles');
s.showGridLines=false;s.getRange('A1:M50').format.font={name:'Arial',size:10};
s.getRange('A1:M50').format.columnWidth=10;s.getRange('A1:M50').format.rowHeight=20;
s.getRange('P1:V1').values=[['Date','A/H premium','CSI 300 return','A-share return','Pair 2','Pair 3','Pair 4']];
const rows=input.rows.map(r=>[r[0],r[1],r[2],r[3],r[1],r[1],r[1]]);
s.getRange(`P2:V${rows.length+1}`).values=rows;
s.getRange(`Q2:V${rows.length+1}`).setNumberFormat('0.0%');
const colors=['#1D4E89','#B17816','#16857A','#6F5598','#B2505D','#486873'];
const chart=s.charts.add('line',s.getRange(`P1:V${rows.length+1}`));
chart.setPosition('A2','M24');chart.title='A/H premium and mainland market';
chart.titleTextStyle.fontSize=15;chart.titleTextStyle.typeface='Arial';
chart.legend={position:'top',textStyle:{typeface:'Arial',fontSize:12}};
chart.xAxis={axisType:'textAxis',textStyle:{typeface:'Arial',fontSize:12}};
chart.yAxis={numberFormatCode:'0%',numberFormatSourceLinked:false,textStyle:{typeface:'Arial',fontSize:12}};
chart.yAxis.title.text='Premium (%)';
chart.series.items.forEach((series,i)=>{series.fill=colors[i];series.line={fill:colors[i],style:i===1?'dashed':'solid',width:i===0?2.6:2.1};});
const market=s.charts.add('line',[s.getRange(`P1:P${rows.length+1}`),s.getRange(`R1:R${rows.length+1}`),s.getRange(`S1:S${rows.length+1}`)]);
market.setPosition('A26','M48');market.title='Mainland market';market.titleTextStyle.fontSize=15;market.titleTextStyle.typeface='Arial';
market.legend={position:'top',textStyle:{typeface:'Arial',fontSize:12}};
market.xAxis={axisType:'textAxis',textStyle:{typeface:'Arial',fontSize:12}};
market.yAxis={numberFormatCode:'0%',numberFormatSourceLinked:false,textStyle:{typeface:'Arial',fontSize:12}};
market.yAxis.title.text='Price return (%)';
market.series.items.forEach((series,i)=>{series.fill=colors[i+1];series.line={fill:colors[i+1],style:i===0?'dashed':'solid',width:2.1};});
wb.recalculate();
console.log((await wb.inspect({kind:'table',range:'AH chart styles!P1:S5',include:'values,formulas',maxChars:1500,tableMaxRows:5,tableMaxCols:4})).ndjson);
const image=await wb.render({sheetName:s.name,range:'A25:M49',scale:1,format:'png'});
await fs.writeFile(new URL('artifact_market_preview.png',out),new Uint8Array(await image.arrayBuffer()));
const x=await SpreadsheetFile.exportXlsx(wb);await x.save(new URL('style_template.xlsx',out).pathname);
console.log('Authored native line styles, titles and typography with Artifact Tool.');
