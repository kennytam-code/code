import fs from 'node:fs/promises';
import {FileBlob,SpreadsheetFile} from '@oai/artifact-tool';
const root=new URL('../',import.meta.url);
const wb=await SpreadsheetFile.importXlsx(await FileBlob.load(new URL('out/_presentation_Database.xlsx',root).pathname));
const s=wb.worksheets.getItem('Database');
s.showGridLines=false;
s.getRange('A1:CF13').format.font.name='Arial';
s.getRange('A1:CF13').format.font.size=10;
s.getRange('A1:CF1').format={font:{name:'Arial',size:17,bold:true,color:'#A9322C'},rowHeight:32};
s.getRange('A2').values=[['']];s.getRange('A2:CF2').format.rowHeight=8;
const bands=[['A3:H3','#CB2125'],['I3:R3','#5D5652'],['S3:AH3','#806344'],['AI3:BD3','#37645D'],['BE3:BO3','#65596C'],['BP3:BW3','#8F4147'],['BX3:CD3','#4B6173'],['CE3:CF3','#60646B']];
for(const [range,color] of bands)s.getRange(range).format={fill:color,font:{name:'Arial',size:10,bold:true,color:'#FFFFFF'},horizontalAlignment:'left',rowHeight:23};
s.getRange('A4:CF4').format={fill:'#F1ECE8',font:{name:'Arial',size:10,bold:true,color:'#36322F'},rowHeight:39,wrapText:true,verticalAlignment:'center',borders:{bottom:{style:'thin',color:'#BEABA3'}}};
for(let r=5;r<=13;r++)s.getRange(`A${r}:CF${r}`).format={rowHeight:29,verticalAlignment:'center',borders:{bottom:{style:'hair',color:'#E1E5EA'}}};
for(const col of ['B','C','D','E','F','G'])s.getRange(`${col}5:${col}13`).format.wrapText=true;
s.getRange('A5:A13').format.horizontalAlignment='left';
s.getRange('B5:B13').format.font.bold=true;
for(const [col,width] of [['A',8],['B',25],['C',14],['D',16],['E',27],['F',29],['G',11],['H',13],['I',15],['J',20],['K',13],['L',13],['M',13],['N',11],['O',11],['P',14],['Q',17],['R',26]])s.getRange(`${col}:${col}`).format.columnWidth=width;
wb.recalculate();
console.log((await wb.inspect({kind:'table',range:'Database!A3:I7',tableMaxRows:5,tableMaxCols:9,maxChars:1200})).ndjson);
const file=await SpreadsheetFile.exportXlsx(wb),path=new URL('out/database_layout.xlsx',root).pathname;
await file.save(path);
await fs.writeFile(new URL('data/database_layout.json',root),JSON.stringify({version:1,xlsx_base64:(await fs.readFile(path)).toString('base64')}));
const image=await wb.render({sheetName:'Database',range:'A1:Q13',scale:1,format:'png'});
await fs.writeFile(new URL('out/database_layout_preview.png',root),new Uint8Array(await image.arrayBuffer()));
console.log('Authored Database presentation; source values retained');
